-- Books v1: shared work catalogue, private reading records, one atomic save.
begin;
create table if not exists public.books (
  id bigint generated by default as identity primary key,
  open_library_work_id text not null unique check (open_library_work_id ~ '^/works/OL[0-9]+W$'),
  title text not null check (length(btrim(title)) between 1 and 1000),
  authors text[] not null check (cardinality(authors) between 1 and 20),
  first_publish_year integer check (first_publish_year between -5000 and 3000),
  cover_id bigint check (cover_id > 0),
  created_at timestamptz not null default now()
);
create table if not exists public.book_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  rating numeric(3,1) not null check (rating between 0.5 and 10 and rating * 2 = trunc(rating * 2)),
  reading_format text not null check (reading_format in ('kindle','audio','unknown')),
  notes text not null default '' check (length(notes) <= 10000),
  updated_at timestamptz not null default now(),
  primary key (user_id, book_id)
);
alter table public.books enable row level security;
alter table public.book_progress enable row level security;
revoke all on public.books, public.book_progress from anon, authenticated;
grant select on public.books to anon, authenticated;
grant select on public.book_progress to authenticated;
drop policy if exists "Anyone reads book catalogue" on public.books;
create policy "Anyone reads book catalogue" on public.books for select to anon, authenticated using (true);
drop policy if exists "Users read own book progress" on public.book_progress;
create policy "Users read own book progress" on public.book_progress for select to authenticated
  using ((select auth.uid()) = user_id);

-- Direct writes are not granted. This function validates the caller, creates
-- the work once, and writes ONLY that caller's progress in one transaction.
create or replace function public.save_book_rating(
  p_work_id text, p_title text, p_authors text[], p_year integer,
  p_cover_id bigint, p_rating numeric, p_format text, p_notes text
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_user uuid := auth.uid();
  v_book public.books%rowtype;
  v_progress public.book_progress%rowtype;
begin
  if v_user is null then raise exception 'Sign in to save a book.' using errcode = '42501'; end if;
  if p_work_id is null or p_work_id !~ '^/works/OL[0-9]+W$'
     or p_title is null or length(btrim(p_title)) not between 1 and 1000
     or p_authors is null or cardinality(p_authors) not between 1 and 20
     or array_ndims(p_authors) <> 1
     or exists (select 1 from unnest(p_authors) a where a is null or length(btrim(a)) not between 1 and 500)
     or (p_year is not null and p_year not between -5000 and 3000)
     or (p_cover_id is not null and p_cover_id <= 0) then
    raise exception 'Invalid book metadata.' using errcode = '22023';
  end if;
  if p_rating is null or p_rating not between 0.5 and 10 or p_rating * 2 <> trunc(p_rating * 2)
     or p_format is null or p_format not in ('kindle','audio','unknown')
     or length(coalesce(p_notes,'')) > 10000 then
    raise exception 'Choose a half-point rating, reading format and notes of at most 10000 characters.' using errcode = '22023';
  end if;
  insert into public.books (open_library_work_id,title,authors,first_publish_year,cover_id)
    values (p_work_id,btrim(p_title),p_authors,p_year,p_cover_id)
    on conflict (open_library_work_id) do nothing;
  select * into strict v_book from public.books where open_library_work_id = p_work_id;
  insert into public.book_progress (user_id,book_id,rating,reading_format,notes)
    values (v_user,v_book.id,p_rating,p_format,coalesce(p_notes,''))
    on conflict (user_id,book_id) do update set
      rating = excluded.rating, reading_format = excluded.reading_format,
      notes = excluded.notes, updated_at = now()
    returning * into v_progress;
  return jsonb_build_object('book',to_jsonb(v_book),'progress',to_jsonb(v_progress));
end;
$$;
revoke all on function public.save_book_rating(text,text,text[],integer,bigint,numeric,text,text) from public, anon;
grant execute on function public.save_book_rating(text,text,text[],integer,bigint,numeric,text,text) to authenticated;
notify pgrst, 'reload schema';
commit;
