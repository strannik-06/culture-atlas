#!/usr/bin/env node
// Refresh TMDB metadata for linked films. Dry-run by default; --apply writes film-details.js.
// TMDB_READ_ACCESS_TOKEN must be provided in environment, never committed.
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
function readGlobal(file,name){const text=fs.readFileSync(path.join(root,file),'utf8');const mark='window.'+name+' = ';return JSON.parse(text.slice(text.indexOf(mark)+mark.length).trim().replace(/;$/,''))}
const catalog=readGlobal('film-catalog.js','CULTURE_CATALOG');
const details=readGlobal('film-details.js','CULTURE_FILM_DETAILS');
const token=process.env.TMDB_READ_ACCESS_TOKEN;
if(!token)throw Error('Missing TMDB_READ_ACCESS_TOKEN');
const apply=process.argv.includes('--apply');
const delay=ms=>new Promise(r=>setTimeout(r,ms));
let updated=0,failed=[];
for(const film of catalog.filter(f=>f.tmdb_id)){
 try{
  const url='https://api.themoviedb.org/3/movie/'+film.tmdb_id+'?append_to_response=credits,external_ids';
  const response=await fetch(url,{headers:{Authorization:'Bearer '+token,accept:'application/json'}});
  if(!response.ok){failed.push({id:film.id,status:response.status});continue}
  const movie=await response.json();
  const current=details[film.id]||{};
  const directors=(movie.credits?.crew||[]).filter(c=>c.job==='Director').map(c=>c.name);
  details[film.id]={...current,tmdb_id:film.tmdb_id,
   title:movie.title,original_title:movie.original_title,overview:movie.overview,
   runtime:movie.runtime,release_date:movie.release_date,
   genres:(movie.genres||[]).map(g=>g.name),
   countries:(movie.production_countries||[]).map(c=>c.iso_3166_1),
   original_language:movie.original_language,
   director:directors.join(', '),
   cast:(movie.credits?.cast||[]).slice(0,5).map(c=>c.name),
   poster:movie.poster_path?'https://image.tmdb.org/t/p/w500'+movie.poster_path:(current.poster||null),
   backdrop:movie.backdrop_path?'https://image.tmdb.org/t/p/w1280'+movie.backdrop_path:null,
   tmdb_rating:movie.vote_average,tmdb_votes:movie.vote_count,
   imdb:{...current.imdb,url:movie.imdb_id?'https://www.imdb.com/title/'+movie.imdb_id+'/':current.imdb?.url}
  };
  updated++;
 }catch(error){failed.push({id:film.id,error:String(error)})}
 await delay(300);
}
if(apply)fs.writeFileSync(path.join(root,'film-details.js'),'// TMDB metadata snapshot; generated by scripts/refresh-tmdb.mjs.\\nwindow.CULTURE_FILM_DETAILS = '+JSON.stringify(details,null,2)+';\\n');
console.log(JSON.stringify({linked:catalog.filter(f=>f.tmdb_id).length,updated,failed,applied:apply},null,2));
if(failed.length)process.exitCode=2;
